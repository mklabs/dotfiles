# Alias

Set-Alias vim nvim
Set-Alias g git
Set-Alias grep findstr

# open => start
Set-Alias -Name open -Value start -Option AllScope

# Terminal alias
Set-Alias -Name q -Value quake -Option AllScope
Set-Alias -Name f -Value floatingterm -Option AllScope

Set-Alias ls lls

# lazygit
Set-Alias lg lazygit
